# 1 WHILE / BREAK / CONTINUE / LAÇO INFINITO

cont = 1  # Valor inicial / Variável de controle

while cont <= 10 :  # teste lógico
    
    print("valor", cont)
    
    cont = cont + 1  # incremento (mudançar no valor testado)
    
    break # finaliza o laço   # continue ^^^^ retorna pra linha do while
    
else:
    print("Fim da repetição.")

